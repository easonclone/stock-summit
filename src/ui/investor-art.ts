/** 用整數格填色，讓斜線在放大後仍保有乾淨的像素邊緣。 */
function polygon(pixel: Pixel, color: string, points: Point[]) {
  const top = Math.min(...points.map(([, y]) => y));
  const bottom = Math.max(...points.map(([, y]) => y));
  for (let y = top; y < bottom; y++) {
    const row = y + 0.5;
    const cuts = points.flatMap(([x, start], i) => {
      const [endX, end] = points[(i + 1) % points.length];
      return (start <= row && row < end) || (end <= row && row < start)
        ? [x + (endX - x) * (row - start) / (end - start)] : [];
    }).sort((a, b) => a - b);
    for (let i = 0; i < cuts.length; i += 2) {
      const left = Math.ceil(cuts[i] - 0.5);
      const right = Math.ceil(cuts[i + 1] - 0.5);
      if (right > left) pixel(color, left, y, right - left, 1);
    }
  }
}

const position = (value: number) => Math.round(value * 1.5);

function brush(pixel: Pixel) {
  const p: Pixel = (color, x, y, w, h) => pixel(color, position(x), position(y) + 2,
    position(x + w) - position(x), position(y + h) - position(y));
  const shape = (color: string, ...points: Point[]) => polygon(pixel, color,
    points.map(([x, y]) => [position(x), position(y) + 2]));
  return { p, shape };
}

